const fs = require('node:fs');
const path = require('node:path');
const corePath = path.resolve(__dirname, '../../extension/core.js');
const catalog = JSON.parse(fs.readFileSync(path.resolve(__dirname, '../../extension/voices.json'), 'utf8'));
fs.writeFileSync(corePath, fs.readFileSync(corePath, 'utf8').replace(/  const voices = \[[\s\S]*?\];/u, '  const voices = ' + JSON.stringify(catalog) + ';'));
fs.copyFileSync(path.resolve(__dirname, '../../app/extension-ui/glass-entry.js'), path.resolve(__dirname, '../../extension/glass.js'));
fs.copyFileSync(path.resolve(__dirname, '../../LICENSE'), path.resolve(__dirname, '../../extension/LICENSE'));
fs.copyFileSync(path.resolve(__dirname, '../../LICENSING.md'), path.resolve(__dirname, '../../extension/LICENSING.md'));
require('./build-app.cjs')();
console.log('Updated voice catalog, native surface adapter and extension licence notices.');
